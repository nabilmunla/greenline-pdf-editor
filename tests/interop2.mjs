// Interop of Ctrl+S on an existing file (changes appended to the file): highlight, save, highlight, save.
import { _electron as electron } from 'playwright';
import { resolve, join } from 'node:path';
import { mkdirSync, copyFileSync, rmSync, statSync } from 'node:fs';
const OUT = resolve('tests/out/interop');
mkdirSync(OUT, { recursive: true });
const F = join(OUT, 'saved-twice.pdf');
copyFileSync(process.argv[2] || 'tests/data/long-spec.pdf', F);
const size0 = statSync(F).size;
rmSync(join(process.env.HOME, '.config', 'PDF Editor', 'profile-interop'), { recursive: true, force: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const app = await electron.launch({ executablePath: resolve('node_modules/electron/dist/electron'), args: [resolve('.'), '--no-sandbox', '--profile=interop'] });
const win = await app.firstWindow();
win.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await app.evaluate(({ BrowserWindow }) => { const b = BrowserWindow.getAllWindows()[0]; b.unmaximize(); b.setContentSize(1500, 950); });
for (let i = 0; i < 60 && !(await win.evaluate(() => !!window.__gcc)); i++) await sleep(200);
await app.evaluate(({ BrowserWindow }, f) => BrowserWindow.getAllWindows()[0].webContents.send('app:open', [f]), F);
await win.waitForFunction(() => window.__gcc.active()?.pages.length > 0);
await sleep(1000);
const E = (fn, a) => win.evaluate(fn, a);
await E(() => window.__gcc.viewer().fit('width')); await sleep(800);
const lineBox = (n) => E(async (n) => { const c = await window.__gcc.active().chars(0); const i = c.text.indexOf(`0.${n} The Contractor`); let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9; for (let k = i; k < i + 40; k++) { const b = c.box.slice(k * 4, k * 4 + 4); if (Number.isNaN(b[0])) continue; x0 = Math.min(x0, b[0]); y0 = Math.min(y0, b[1]); x1 = Math.max(x1, b[2]); y1 = Math.max(y1, b[3]); } return [x0, y0, x1, y1]; }, n);
const at = async (x, y) => { const box = await win.locator('.pg[data-page="0"]').boundingBox(); const w = await E(() => window.__gcc.active().pages[0].w); const k = box.width / w; return [box.x + x * k, box.y + y * k]; };
const hl = async (n) => { await win.locator('.rtab', { hasText: /^Comment$/ }).click(); await win.locator('.ribbon [data-tool="highlight"]').click(); const b = await lineBox(n); const p = await at(b[0] + 1, (b[1] + b[3]) / 2), q = await at(b[2] - 2, (b[1] + b[3]) / 2); await win.mouse.move(p[0], p[1]); await win.mouse.down(); await win.mouse.move(q[0], q[1], { steps: 10 }); await win.mouse.up(); await sleep(600); await win.keyboard.press('Escape'); };
await hl(2);
await win.keyboard.press('Control+s'); await sleep(1500);
const size1 = statSync(F).size;
await hl(6);
await win.keyboard.press('Control+s'); await sleep(1500);
const size2 = statSync(F).size;
console.log('sizes: original', size0, '-> first save', size1, '-> second save', size2, '(appended:', size1 > size0 ? 'yes' : 'no', ')');
await app.evaluate(({ app: a }) => a.exit(0)).catch(() => {});
process.exit(0);
