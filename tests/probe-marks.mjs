// Probe: page numbers + watermark on a 1,504-page file whose first pages are dense drawings.
import { _electron as electron } from 'playwright';
import { resolve, join } from 'node:path';
import { rmSync, copyFileSync } from 'node:fs';
const F = resolve('tests/tmp-probe/merged-copy.pdf'); copyFileSync('tests/tmp-probe/merged.pdf', F);
rmSync(join(process.env.HOME, '.config', 'PDF Editor', 'profile-probe'), { recursive: true, force: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const app = await electron.launch({ executablePath: resolve('node_modules/electron/dist/electron'), args: [resolve('.'), '--no-sandbox', '--profile=probe'] });
const win = await app.firstWindow();
await app.evaluate(({ BrowserWindow }) => { const b = BrowserWindow.getAllWindows()[0]; b.unmaximize(); b.setContentSize(1600, 1000); });
await win.waitForFunction(() => !!window.__gcc, null, { timeout: 60000 });
const E = (fn, a) => win.evaluate(fn, a);
await app.evaluate(({ BrowserWindow }, p) => BrowserWindow.getAllWindows()[0].webContents.send('app:open', [p]), F);
await win.waitForFunction(() => window.__gcc.active()?.pages.length > 1000, null, { timeout: 60000 });
const idle = async () => { const t = Date.now(); while (Date.now() - t < 120000) { const s = await E(() => window.__gcc.tiles.stats()).catch(() => null); if (s && s.tiles > 0 && !s.queued && !s.inflight) return Date.now() - t; await sleep(100); } return -1; };
console.log('first pictures', await idle(), 'ms');
await E(() => window.__gccSlow.splice(0));
const t0 = await E(() => performance.now());
const stats = () => E(async () => Promise.all(window.__gcc.engines.renderers.map((r) => r.call('pageStats'))));
console.log('engines before:', JSON.stringify(await stats()));
let t = Date.now();
await win.locator('.rtab', { hasText: 'Edit' }).click();
await win.locator('.ribbon .rb', { hasText: 'Numbers & headers' }).click();
await win.locator('.modal .mbox', { hasText: 'Watermark' }).locator('input[type=checkbox]').first().check();
await win.locator('.modal button', { hasText: 'Apply to this file' }).click();
await win.waitForFunction(() => !document.querySelector('.modal'), null, { timeout: 120000 }).catch(() => {});
console.log('marks applied (dialog closed)', Date.now() - t, 'ms');
const ok = await E(async () => { const d = window.__gcc.active(); const c = await d.chars(0); return c.text.includes('Page 1 of') && c.text.includes('FOR TENDER'); });
console.log('text check', ok, Date.now() - t, 'ms');
console.log('engines after:', JSON.stringify(await stats()));
const s = await E(() => window.__gccSlow.splice(0));
for (const c of s) console.log(`${String(Math.round(c.at - t0)).padStart(6)} +${String(c.ms).padStart(6)}  ${c.engine}.${c.method}`);
await app.evaluate(({ app: a }) => a.exit(0)).catch(() => {});
process.exit(0);
