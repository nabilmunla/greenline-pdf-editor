import { _electron as electron } from 'playwright';
import { resolve } from 'node:path';
const app = await electron.launch({ executablePath: resolve('node_modules/electron/dist/electron'), args: [resolve('.'), '--no-sandbox', '--profile=repro3', resolve('tests/real/ga-l00-19mb.pdf')] });
const win = await app.firstWindow();
win.on('console', (m) => console.log('console', m.type(), m.text().slice(0, 200)));
await win.setViewportSize({ width: 1600, height: 1000 }).catch(() => {});
await win.waitForFunction(() => window.__gcc && window.__gcc.active());
await win.waitForTimeout(1500);
const at = async (x, y) => { const b = await win.locator('.pg[data-page="0"]').boundingBox(); const k = b.width / (await win.evaluate(() => window.__gcc.active().pages[0].w)); return [b.x + x * k, b.y + y * k, k]; };
const ann = () => win.evaluate(async () => (await window.__gcc.active().allAnnots()).map((a) => a.type + ' ' + a.rect.map(Math.round).join(',')));
const drag = async (a, b) => { const p = await at(...a), q = await at(...b); await win.mouse.move(p[0], p[1]); await win.mouse.down(); await win.mouse.move(q[0], q[1], { steps: 8 }); await win.mouse.up(); };
await win.locator('.rtab', { hasText: 'Comment' }).click();
await win.locator('.ribbon .rb', { hasText: 'Rectangle' }).click();
await drag([1000, 800], [1400, 1100]);
await win.waitForTimeout(800);
console.log('drawn', await ann());
await drag([1000, 950], [1200, 1050]);
await win.waitForTimeout(800);
console.log('moved', await ann(), 'sel', await win.evaluate(() => document.querySelector('.ov polygon.selbox')?.getAttribute('points')));
const [, , k] = await at(0, 0);
const a = (await win.evaluate(async () => (await window.__gcc.active().allAnnots())[0].rect));
await drag([a[2] + 5 / k, a[3] + 5 / k], [a[2] + 200, a[3] + 100]);
await win.waitForTimeout(800);
console.log('resized', await ann());
process.exit(0);
