// Bridge between the interface and the PC.
'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

// engine ports: handed to the page (ports can't cross the bridge as arguments)
ipcRenderer.on('engine:port', (e, info) => { window.postMessage({ type: 'engine-port', ...info }, '*', e.ports); });
ipcRenderer.on('engine:gaveUp', (_e, info) => { window.postMessage({ type: 'engine-gaveup', ...info }, '*'); });

/** a failed file call: just its own message ("…is open in another program"), not Electron's
 *  "Error invoking remote method 'file:write': Error: …" in front of it */
function plainError(e) {
  throw new Error(String((e && e.message) || e).replace(/^Error invoking remote method '[^']+': (Error: )?/, ''));
}

contextBridge.exposeInMainWorld('gcc', {
  /** drawing engines asked for on the command line (tests), 0 = by the PC */
  renderers: Number((process.argv.find((a) => a.startsWith('--gcc-renderers=')) || '').split('=')[1]) || 0,
  info: () => ipcRenderer.invoke('app:info'),
  user: () => ipcRenderer.invoke('app:user'),
  settings: () => ipcRenderer.invoke('settings:get'),
  viewGet: (p) => ipcRenderer.invoke('view:get', p),
  viewSet: (p, v) => ipcRenderer.invoke('view:set', p, v),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  onSettings: (cb) => ipcRenderer.on('settings:changed', (_e, patch) => cb(patch || {})),
  setTheme: (mode) => ipcRenderer.invoke('win:theme', mode),
  setTitle: (t) => ipcRenderer.invoke('win:title', t),
  read: (p) => ipcRenderer.invoke('file:read', p),
  stat: (p) => ipcRenderer.invoke('file:stat', p),
  write: (p, data, opts) => ipcRenderer.invoke('file:write', p, data, opts).catch(plainError),
  exists: (p) => ipcRenderer.invoke('file:exists', p),
  listPdfs: (dir, recursive, kind) => ipcRenderer.invoke('file:list', dir, recursive, kind),
  systemFont: (name) => ipcRenderer.invoke('file:systemFont', name),
  cacheGet: (k) => ipcRenderer.invoke('cache:get', k),
  cachePut: (k, data) => ipcRenderer.invoke('cache:put', k, data),
  recoveryWrite: (key, data, meta) => ipcRenderer.invoke('recovery:write', key, data, meta),
  recoveryClear: (key) => ipcRenderer.invoke('recovery:clear', key),
  recoveryList: () => ipcRenderer.invoke('recovery:list'),
  openDialog: (opts) => ipcRenderer.invoke('dialog:open', opts),
  saveDialog: (opts) => ipcRenderer.invoke('dialog:save', opts),
  dirDialog: (opts) => ipcRenderer.invoke('dialog:dir', opts),
  confirm: (o) => ipcRenderer.invoke('dialog:confirm', o),
  copyImage: (png) => ipcRenderer.invoke('clip:image', png),
  copyText: (t, html) => ipcRenderer.invoke('clip:text', t, html),
  pasteImage: () => ipcRenderer.invoke('clip:readImage'),
  showInFolder: (p) => ipcRenderer.invoke('shell:show', p),
  openExternal: (p) => ipcRenderer.invoke('shell:open', p),
  openLink: (u) => ipcRenderer.invoke('shell:link', u),
  /** the page listens for files to open now */
  ready: () => ipcRenderer.send('app:ready'),
  print: (data, name) => ipcRenderer.invoke('app:print', data, name),
  printers: () => ipcRenderer.invoke('print:printers'),
  sessionPrinter: (name) => ipcRenderer.invoke('print:sessionPrinter', name),
  printRun: (file, o) => ipcRenderer.invoke('print:run', file, o),
  printPrefs: (name) => ipcRenderer.invoke('print:prefs', name),
  aiKeys: () => ipcRenderer.invoke('ai:keys'),
  aiSetKey: (provider, key, check) => ipcRenderer.invoke('ai:setKey', provider, key, !!check),
  aiModels: (provider) => ipcRenderer.invoke('ai:models', provider),
  aiSend: (id, provider, req) => ipcRenderer.invoke('ai:send', id, provider, req),
  aiCancel: (id) => ipcRenderer.invoke('ai:cancel', id),
  onAiEvent: (cb) => { const f = (_e, id, ev) => cb(id, ev); ipcRenderer.on('ai:event', f); return () => ipcRenderer.removeListener('ai:event', f); },
  mtLanguages: () => ipcRenderer.invoke('mt:languages'),
  mtStatus: (from, to) => ipcRenderer.invoke('mt:status', from, to),
  mtInstall: (from, to) => ipcRenderer.invoke('mt:install', from, to),
  mtTranslate: (from, to, texts) => ipcRenderer.invoke('mt:translate', from, to, texts),
  onMtProgress: (cb) => { const f = (_e, pair, done, total) => cb(pair, done, total); ipcRenderer.on('mt:progress', f); return () => ipcRenderer.removeListener('mt:progress', f); },
  htmlToPdf: (html, name, opts) => ipcRenderer.invoke('html:toPdf', html, name, opts),
  enginesStart: (list) => ipcRenderer.invoke('engines:start', list),
  commit: (src, file, opts) => ipcRenderer.invoke('file:commit', src, file, opts).catch(plainError),
  toTemp: (src) => ipcRenderer.invoke('file:toTemp', src),
  dropTemp: (paths) => ipcRenderer.invoke('file:dropTemp', paths),
  docsClosed: () => ipcRenderer.send('docs:closed'),
  recoveryPath: (key) => ipcRenderer.invoke('recovery:path', key),
  recoveryMeta: (key, meta) => ipcRenderer.invoke('recovery:meta', key, meta),
  dragPrepare: (data, name) => ipcRenderer.invoke('drag:prepare', data, name),
  dragStart: (file, png) => ipcRenderer.send('drag:start', file, png),
  registerOpenWith: () => ipcRenderer.invoke('app:registerOpenWith'),
  pathOf: (file) => { try { return webUtils.getPathForFile(file); } catch (_) { return ''; } },
  onOpen: (cb) => ipcRenderer.on('app:open', (_e, files) => cb(files)),
  onCombine: (cb) => ipcRenderer.on('app:combine', (_e, files) => cb(files)),
  onClosing: (cb) => ipcRenderer.on('app:closing', (_e, o) => cb(o || {})),
  onRedraw: (cb) => ipcRenderer.on('app:redraw', (_e, why) => cb(String(why || ''))),
  closeCancelled: () => ipcRenderer.send('app:closeCancelled'),
  updateGet: () => ipcRenderer.invoke('update:get'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateDownload: () => ipcRenderer.invoke('update:download'),
  updateCancel: () => ipcRenderer.invoke('update:cancel'),
  updateLater: () => ipcRenderer.invoke('update:later'),
  updateSource: (v) => ipcRenderer.invoke('update:source', v),
  updateRestart: (now) => ipcRenderer.invoke('update:restart', now),
  updateRollback: () => ipcRenderer.invoke('update:rollback'),
  updateAfterStart: () => ipcRenderer.invoke('update:afterStart'),
  reportCapture: () => ipcRenderer.invoke('report:capture'),
  reportProblem: (text, withShot, extra) => ipcRenderer.invoke('report:problem', text, withShot, extra),
  reportStatus: () => ipcRenderer.invoke('report:status'),
  reportCrashSharing: (on) => ipcRenderer.invoke('report:crashSharing', on),
  reportPreview: () => ipcRenderer.invoke('report:preview'),
  reportOpenQueue: () => ipcRenderer.invoke('report:openQueue'),
  reportCrash: (where, message, stack) => ipcRenderer.send('report:crash', where, message, stack),
  onReports: (cb) => { const f = () => cb(); ipcRenderer.on('reports:state', f); return () => ipcRenderer.removeListener('reports:state', f); },
  onUpdate: (cb) => { const f = (_e, st) => cb(st); ipcRenderer.on('update:state', f); return () => ipcRenderer.removeListener('update:state', f); },
  closed: () => ipcRenderer.send('app:closed'),
  /** tabs between windows: where this window's tab strip is; which window is at a screen point;
   *  move a file to that window (or a new one) - resolves once it's open there */
  tabStrip: (r) => ipcRenderer.send('tabs:strip', r),
  tabPaths: (list) => ipcRenderer.send('tabs:paths', list),
  tabsElsewhere: () => ipcRenderer.invoke('tabs:elsewhere'),
  tabTarget: (x, y) => ipcRenderer.invoke('tabs:target', x, y),
  tabHover: (x, y) => ipcRenderer.send('tabs:hover', x, y),
  tabMove: (payload, target, x, y) => ipcRenderer.invoke('tabs:move', payload, target, x, y),
  onAdopt: (cb) => ipcRenderer.on('app:adopt', (_e, p) => cb(p)),
  adopted: (id, ok) => ipcRenderer.send('tabs:adopted', id, ok),
  onTabHover: (cb) => ipcRenderer.on('tabs:hover', (_e, on) => cb(!!on)),
  windowCount: () => ipcRenderer.invoke('win:count'),
  log: (line) => ipcRenderer.send('log', String(line)),
});
